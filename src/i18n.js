// Jäädyttää tekstit, koska samaa oliota jaetaan kaikille komponenteille.
function jaadyta(olio) {
  Object.values(olio).forEach((arvo) => {
    if (arvo && typeof arvo === 'object') jaadyta(arvo);
  });
  return Object.freeze(olio);
}

